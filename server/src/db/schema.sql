create table if not exists units (
  id text primary key,
  order_index integer not null unique,
  title_es text not null,
  title_pt text not null
);

create table if not exists lessons (
  id text primary key,
  unit_id text not null references units (id) on delete cascade,
  order_index integer not null,
  title_es text not null,
  title_pt text not null,
  unique (unit_id, order_index)
);

create table if not exists exercises (
  lesson_id text not null references lessons (id) on delete cascade,
  id text not null,
  format text not null check (format in ('seta', 'verdadeiro-falso', 'completar', 'associacao')),
  order_index integer not null,
  data_es jsonb not null,
  data_pt jsonb not null,
  primary key (lesson_id, id)
);

create index if not exists lessons_unit_id_order_idx on lessons (unit_id, order_index);
create index if not exists exercises_lesson_id_order_idx on exercises (lesson_id, order_index);

create table if not exists profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  onboarding_completed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table profiles add column if not exists onboarding_completed boolean not null default false;

create table if not exists lesson_progress (
  user_id uuid not null references auth.users (id) on delete cascade,
  lesson_id text not null references lessons (id) on delete cascade,
  score integer not null default 0,
  correct_count integer not null default 0,
  total_exercises integer not null default 0,
  completed_at timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

create table if not exists exercise_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  lesson_id text not null references lessons (id) on delete cascade,
  exercise_id text not null,
  is_correct boolean not null,
  points integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists user_streaks (
  user_id uuid primary key references auth.users (id) on delete cascade,
  current_streak integer not null default 0,
  longest_streak integer not null default 0,
  last_activity_date date,
  updated_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (user_id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', ''))
  on conflict (user_id) do nothing;
  insert into public.user_streaks (user_id)
  values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

alter table units enable row level security;
alter table lessons enable row level security;
alter table exercises enable row level security;
alter table profiles enable row level security;
alter table lesson_progress enable row level security;
alter table exercise_attempts enable row level security;
alter table user_streaks enable row level security;

drop policy if exists profiles_owner_select on profiles;
create policy profiles_owner_select on profiles for select using (auth.uid() = user_id);
drop policy if exists profiles_owner_update on profiles;
create policy profiles_owner_update on profiles for update using (auth.uid() = user_id);
drop policy if exists progress_owner_all on lesson_progress;
create policy progress_owner_all on lesson_progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists attempts_owner_all on exercise_attempts;
create policy attempts_owner_all on exercise_attempts for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists streaks_owner_all on user_streaks;
create policy streaks_owner_all on user_streaks for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

grant usage on schema public to service_role;
grant select, insert, update, delete on units, lessons, exercises to service_role;
grant select, insert, update, delete on profiles, lesson_progress, exercise_attempts, user_streaks to service_role;
